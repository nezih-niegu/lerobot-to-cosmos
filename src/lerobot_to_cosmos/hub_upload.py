"""Upload a converted dataset to the Hugging Face Hub with the ``hf`` CLI.

The token is asked for interactively (hidden input) unless ``HF_TOKEN`` is set. It is only
handed to the ``hf`` child processes through their environment: it is never written to
disk, never put on a command line (where shell history or ``ps`` could show it) and never
printed.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

from .hub import _HF_LINK

REPO_ID_RE = re.compile(r"^[A-Za-z0-9][\w.-]{0,95}/[A-Za-z0-9][\w.-]{0,95}$")
TOKEN_RE = re.compile(r"^hf_[A-Za-z0-9]{20,}$")
CARD_MARKER = "<!-- generated by lerobot-to-cosmos -->"
PATH_RE = re.compile(r"^[A-Za-z0-9][\w.-]*(/[A-Za-z0-9][\w.-]*)*$")
# What a dataset uploaded to the repo root consists of (used by --clean-root).
ROOT_DATASET_PATTERNS = ["train/*", "val/*", "conversion_summary.json", "cosmos_loader_check.json",
                         "cosmos_loader_preview.png"]
TOKEN_URL = "https://huggingface.co/settings/tokens/new?tokenType=fineGrained"


class UploadError(RuntimeError):
    pass


def log(msg: str = "") -> None:
    print(msg, flush=True)


def check_repo_id(repo_id: str) -> str:
    repo_id = repo_id.strip()
    if repo_id.startswith("https://huggingface.co/datasets/"):
        repo_id = repo_id.removeprefix("https://huggingface.co/datasets/").strip("/")
    if not REPO_ID_RE.match(repo_id):
        raise UploadError(f"--push-to-hub needs a dataset id like 'your-name/so101-cups-cosmos', got {repo_id!r}")
    return repo_id


def check_path_in_repo(path: str | None) -> str | None:
    if path is None:
        return None
    path = path.strip().strip("/")
    if not path or path == ".":
        return None
    if not PATH_RE.match(path) or ".." in path.split("/"):
        raise UploadError(f"--path-in-repo must be a folder name like '30fps' or 'versions/30fps', got {path!r}")
    return path


def get_token(prompt: Callable[..., str], attempts: int = 3) -> str:
    """HF_TOKEN from the environment, else ask (hidden input) for a fine-grained hf_ token."""
    env_token = os.environ.get("HF_TOKEN", "").strip()
    if env_token:
        if not TOKEN_RE.match(env_token):
            raise UploadError("HF_TOKEN is set but doesn't look like a Hugging Face token (hf_...).")
        log("Using the Hugging Face token from the HF_TOKEN environment variable.")
        return env_token
    log(f"Uploading needs a Hugging Face fine-grained token with write access to the target namespace.\n"
        f"Create one at {TOKEN_URL}\n"
        f"(Repositories permissions: 'Write access to contents/settings of all repos under your personal "
        f"namespace', or the same for an organization). It is used for this run only and not saved.")
    for _ in range(attempts):
        token = prompt("Hugging Face fine-grained token (hf_...)", hide_input=True).strip()
        if TOKEN_RE.match(token):
            return token
        log("That doesn't look like a Hugging Face token (it should start with 'hf_'). Try again.")
    raise UploadError("No valid Hugging Face token entered.")


def check_token(token: str, repo_id: str) -> str:
    """Confirm the token works and can write to the repo's namespace. Returns the account name."""
    from huggingface_hub import HfApi
    from huggingface_hub.errors import HfHubHTTPError

    try:
        info = HfApi().whoami(token=token)
    except HfHubHTTPError as e:
        raise UploadError(f"Hugging Face rejected the token ({e.__class__.__name__}). "
                          f"Check it hasn't expired or been revoked.") from None
    user = info.get("name", "?")
    orgs = [o.get("name") for o in info.get("orgs", []) if isinstance(o, dict)]
    namespace = repo_id.split("/")[0]
    access = (info.get("auth") or {}).get("accessToken") or {}
    role = access.get("role")
    log(f"Token OK: account '{user}'" + (f", token '{access['displayName']}'" if access.get("displayName") else "")
        + (f" ({role})" if role else ""))
    if namespace != user and namespace not in orgs:
        raise UploadError(f"'{namespace}' is neither your account ('{user}') nor one of your organizations "
                          f"{orgs or '[]'}; choose a repo id under your namespace.")
    if role and role != "fineGrained":
        log(f"note: this is a '{role}' token, not a fine-grained one. A fine-grained token limited to "
            f"'{namespace}' is safer: {TOKEN_URL}")
    if role == "read":
        raise UploadError("This token is read-only; uploading needs write access.")
    if role == "fineGrained":
        fg = access.get("fineGrained") or {}
        perms = set(fg.get("global") or [])
        for scope in fg.get("scoped") or []:
            if (scope.get("entity") or {}).get("name") == namespace:
                perms |= set(scope.get("permissions") or [])
        if perms and not any("write" in p for p in perms):
            raise UploadError(f"This fine-grained token has no write permission for '{namespace}' "
                              f"(it has: {sorted(perms)}). Edit it at https://huggingface.co/settings/tokens.")
    return user


def hf_cli() -> str:
    exe = shutil.which("hf")
    if not exe:
        sibling = Path(sys.executable).with_name("hf")
        if sibling.exists():
            exe = str(sibling)
    if not exe:
        raise UploadError("The Hugging Face CLI ('hf') was not found; it ships with huggingface_hub (uv sync).")
    return exe


def run_hf(args: list[str], token: str, quiet: bool = False) -> str:
    cmd = [hf_cli(), *args]
    if not quiet:
        log("$ hf " + " ".join(args))
    env = {**os.environ, "HF_TOKEN": token, "NO_COLOR": "1"}
    res = subprocess.run(cmd, env=env, capture_output=True, text=True, check=False)
    out = (res.stdout + res.stderr).replace(token, "hf_***")
    if out.strip() and not (quiet and res.returncode == 0):
        log(out.rstrip())
    if res.returncode != 0:
        raise UploadError(f"'hf {args[0]}' failed (exit {res.returncode}).")
    return out


# --------------------------------------------------------------------------- dataset card
def source_license(source: str | None, token: str) -> str | None:
    """License declared on the source dataset's card, if the source is a Hub dataset."""
    if not source or Path(source).expanduser().exists():
        return None
    m = _HF_LINK.match(source.strip())
    if not m:
        return None
    try:
        from huggingface_hub import HfApi

        card = HfApi().dataset_info(m.group(1), token=token).card_data
        lic = card.get("license") if card else None
        return lic if isinstance(lic, str) else None
    except Exception:  # noqa: BLE001 - the card is optional
        return None


def usage_lines(repo_id: str, path_in_repo: str | None) -> list[str]:
    local = repo_id.split("/")[-1]
    if path_in_repo:
        return [f'hf download {repo_id} --repo-type dataset --include "{path_in_repo}/*" --local-dir {local}',
                f"export DATASET_PATH=$PWD/{local}/{path_in_repo}   # then, in cosmos-framework:",
                "bash examples/launch_sft_vision_nano.sh"]
    return [f"hf download {repo_id} --repo-type dataset --local-dir {local}",
            f"export DATASET_PATH=$PWD/{local}   # then, in cosmos-framework:",
            "bash examples/launch_sft_vision_nano.sh"]


def write_card(out: Path, repo_id: str, token: str, path_in_repo: str | None = None) -> Path | None:
    readme = out / "README.md"
    if readme.exists() and CARD_MARKER not in readme.read_text(encoding="utf-8", errors="replace"):
        log("Keeping your own README.md (not generated by lerobot-to-cosmos).")
        return None
    s = json.loads((out / "conversion_summary.json").read_text(encoding="utf-8")) \
        if (out / "conversion_summary.json").exists() else {}
    loader = json.loads((out / "cosmos_loader_check.json").read_text(encoding="utf-8")) \
        if (out / "cosmos_loader_check.json").exists() else None
    settings = s.get("settings", {})
    source, reference = s.get("source"), s.get("reference")
    n_train = s.get("train_jsonl", {}).get("records", len(list((out / "train" / "videos").glob("*.mp4"))))
    n_val = len(list((out / "val" / "videos").glob("*.mp4"))) if (out / "val" / "videos").exists() else 0
    n_cj = s.get("train_jsonl", {}).get("with_caption_json", 0)
    cams = settings.get("cameras", [])
    lic = source_license(source, token)

    front = ["---", "tags:", "- robotics", "- lerobot", "- cosmos", "- video", "task_categories:", "- robotics"]
    if lic:
        front.append(f"license: {lic}")
    front += ["viewer: false", "---"]
    if path_in_repo:
        front = []  # only the repo-root README is the dataset card; sub-folder READMEs are plain pages
    src_link = f"[{source.split('datasets/')[-1]}]({source})" if source and source.startswith("http") else (source or "a LeRobot dataset")
    ref_link = f"[{reference.split('datasets/')[-1]}]({reference})" if reference and reference.startswith("http") else (reference or "the Cosmos video-SFT format")
    title = repo_id.split("/")[-1] + (f" / {path_in_repo}" if path_in_repo else "")
    body = [CARD_MARKER, f"# {title}", "",
            (f"{src_link} converted to the NVIDIA Cosmos3 video-SFT format, laid out like {ref_link}, "
            f"with lerobot-to-cosmos. Ready for the `vision_sft_*` recipes in "
            f"[cosmos-framework](https://github.com/nvidia/cosmos-framework)."), "",
            "| | |", "|---|---|",
            f"| Training clips | {n_train} (`train/video_dataset_file.jsonl`) |",
            f"| Validation clips | {n_val} (with t2v / i2v / v2v prompts in `val/`) |"]
    if s.get("episodes_exported"):
        body.append(f"| Episodes | {s['episodes_exported']} |")
    if cams:
        cam_names = ", ".join("`" + c.split(".")[-1] + "`" for c in cams)
        body.append(f"| Cameras | {cam_names} (one clip per camera) |")
    if settings.get("width"):
        body.append(f"| Clips | {settings['width']}x{settings['height']}, {settings.get('fps', 0):g} fps, "
                    f"{settings.get('resize_mode', 'crop')} |")
    body.append(f"| Captions | {'structured `caption_json` + ' if n_cj else ''}dense `caption` "
                f"({'from a VLM captioner' if n_cj else 'template from the task string'}) |")
    if loader:
        status = "passed" if not loader.get("errors") else f"{len(loader['errors'])} problems"
        body.append(f"| Cosmos loader check | {status}: {loader.get('passed', 0)}/{loader.get('checked', 0)} clips "
                    f"through cosmos-framework's SFT loader (`{loader.get('recipe', '')}`) |")
    depth = settings.get("depth") or {}
    if depth:
        body += ["", "## Depth", ""]
        for cam, d in depth.items():
            body.append(f"`{cam.split('.')[-1]}` clips are rendered depth: LeRobot's 12-bit log-quantized depth "
                        f"decoded to metres and drawn as grayscale inverse depth, white at {d['near_m']} m, black at "
                        f"{d['far_m']} m and beyond; black also marks pixels with no depth reading.")
    if settings.get("val_holdout") is False:
        body += ["", "The validation episodes are also part of `train/`; `val/` is for inference previews."]
    body += ["", "## Use with Cosmos", "", "```bash", *usage_lines(repo_id, path_in_repo), "```", "",
             "`conversion_summary.json` lists every clip with its source episode, camera and time range."]
    if lic:
        body += ["", f"License carried over from the source dataset: `{lic}`."]
    readme.write_text("\n".join(front + body) + "\n", encoding="utf-8")
    return readme


# --------------------------------------------------------------------------- upload
def list_repo(repo_id: str, token: str) -> list[str]:
    from huggingface_hub import HfApi

    try:
        return list(HfApi().list_repo_files(repo_id, repo_type="dataset", token=token))
    except Exception:  # noqa: BLE001 - repo may not exist yet
        return []


def variants_in(files: list[str]) -> list[str]:
    """Folders of the repo (any depth) that hold a complete Cosmos dataset."""
    suffix = "/train/video_dataset_file.jsonl"
    return sorted(f[: -len(suffix)] for f in files if f.endswith(suffix))


def hf_fetch(repo_id: str, filename: str, token: str, dest: Path) -> Path | None:
    """Download one file with the hf CLI; None if it doesn't exist."""
    try:
        run_hf(["download", repo_id, filename, "--repo-type", "dataset", "--local-dir", str(dest), "--quiet"],
               token, quiet=True)
    except UploadError:
        return None
    f = dest / filename
    return f if f.exists() else None


def write_index_card(repo_id: str, token: str, files: list[str], lic: str | None, tmp: Path) -> Path | None:
    """Root README for a repo holding several dataset versions in sub-folders."""
    if "README.md" in files:
        current = hf_fetch(repo_id, "README.md", token, tmp / "current")
        if current and CARD_MARKER not in current.read_text(encoding="utf-8", errors="replace"):
            log("Keeping the repo's own README.md at the root (not generated by lerobot-to-cosmos).")
            return None
    rows = []
    for v in variants_in(files):
        s = {}
        if f"{v}/conversion_summary.json" in files:
            got = hf_fetch(repo_id, f"{v}/conversion_summary.json", token, tmp / "summaries")
            if got:
                s = json.loads(got.read_text(encoding="utf-8"))
        st = s.get("settings", {})
        clips = s.get("train_jsonl", {}).get("records", "")
        fmt = f"{st['width']}x{st['height']}, {st.get('fps', 0):g} fps" if st.get("width") else ""
        cams = len(st.get("cameras", [])) or ""
        link = f"https://huggingface.co/datasets/{repo_id}/blob/main/{v}/README.md"
        rows.append(f"| [`{v}/`]({link}) | {fmt} | {clips} | {cams} |")
    front = ["---", "tags:", "- robotics", "- lerobot", "- cosmos", "- video", "task_categories:", "- robotics"]
    if lic:
        front.append(f"license: {lic}")
    front += ["viewer: false", "---"]
    first = variants_in(files)[0] if variants_in(files) else "VERSION"
    body = [CARD_MARKER, f"# {repo_id.split('/')[-1]}", "",
            ("NVIDIA Cosmos3 video-SFT datasets converted from a LeRobot v3.0 dataset with lerobot-to-cosmos. "
             "Each folder below is a complete dataset (its own `train/`, `val/` and card); pick one."), "",
            "| Version | Format | Training clips | Cameras |", "|---|---|---|---|", *rows, "",
            "## Use with Cosmos", "", "```bash", *usage_lines(repo_id, first), "```"]
    readme = tmp / "index" / "README.md"
    readme.parent.mkdir(parents=True, exist_ok=True)
    readme.write_text("\n".join(front + body) + "\n", encoding="utf-8")
    return readme


def upload(out: Path, repo_id: str, token: str, private: bool, path_in_repo: str | None = None,
           clean_root: bool = False) -> str:
    import tempfile

    path_in_repo = check_path_in_repo(path_in_repo)
    if not (out / "train" / "video_dataset_file.jsonl").is_file():
        raise UploadError(f"{out} has no train/video_dataset_file.jsonl; convert first.")
    summary = out / "conversion_summary.json"
    if summary.exists():
        errs = json.loads(summary.read_text(encoding="utf-8")).get("validation", {}).get("errors")
        if errs:
            raise UploadError(f"Not uploading: the last conversion failed validation ({len(errs)} errors).")
    user = check_token(token, repo_id)

    files = list_repo(repo_id, token)
    root_dataset = "train/video_dataset_file.jsonl" in files
    if path_in_repo and root_dataset and not clean_root:
        raise UploadError(
            f"datasets/{repo_id} already has a dataset at its root (train/, val/), probably an earlier upload "
            f"without --path-in-repo. Two layouts in one repo would be confusing. Either upload that version "
            f"into its own folder too and rerun this with --clean-root (deletes the root train/, val/ and "
            f"summary files from the Hub; your local copy is untouched), or pick another repo.")
    if not path_in_repo and variants_in(files) and not root_dataset:
        log(f"note: this repo already holds versions in folders {variants_in(files)}; consider "
            f"--path-in-repo so this upload gets its own folder too.")

    write_card(out, repo_id, token, path_in_repo)
    n_files = sum(1 for p in out.rglob("*") if p.is_file() and p.name != ".DS_Store")
    size_mb = sum(p.stat().st_size for p in out.rglob("*") if p.is_file()) / 1e6
    where = f"datasets/{repo_id}/{path_in_repo}/" if path_in_repo else f"datasets/{repo_id}"
    log(f"\nUploading {out} ({n_files} files, {size_mb:.0f} MB) to {where} "
        f"({'private' if private else 'public'} if the repo is new) ...")
    run_hf(["repos", "create", repo_id, "--repo-type", "dataset", "--private" if private else "--public",
            "--exist-ok"], token)
    run_hf(["upload", repo_id, str(out), path_in_repo or ".", "--repo-type", "dataset",
            "--exclude", ".DS_Store", "--exclude", "**/.DS_Store",
            "--commit-message", f"Upload Cosmos video-SFT dataset ({path_in_repo or out.name}) via lerobot-to-cosmos"],
           token)

    if path_in_repo:
        if root_dataset and clean_root:
            run_hf(["repos", "delete-files", repo_id, *ROOT_DATASET_PATTERNS, "--repo-type", "dataset",
                    "--commit-message", "Remove root-level dataset (versions now live in folders)"], token)
        files = list_repo(repo_id, token)
        with tempfile.TemporaryDirectory() as tmp:
            s = json.loads(summary.read_text(encoding="utf-8")) if summary.exists() else {}
            index = write_index_card(repo_id, token, files, source_license(s.get("source"), token), Path(tmp))
            if index:
                run_hf(["upload", repo_id, str(index), "README.md", "--repo-type", "dataset",
                        "--commit-message", "Update dataset card (index of versions)"], token)
    url = f"https://huggingface.co/datasets/{repo_id}" + (f"/tree/main/{path_in_repo}" if path_in_repo else "")
    log(f"\nUploaded by '{user}': {url}")
    return url
